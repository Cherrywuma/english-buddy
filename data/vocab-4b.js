// === Word lists 总词汇表 (书末第 76-77 页) ===
window.VOCAB_4B.wordLists = [];
window.VOCAB_4B.units.forEach(unit => {
  if (!unit.words) return;
  unit.words.forEach(w => {
    if (!window.VOCAB_4B.wordLists.find(x => x.en === w.en)) {
      window.VOCAB_4B.wordLists.push({
        ...w,
        unitId: unit.id,
        unitTitle: unit.title,
        unitTitleZh: unit.titleZh
      });
    }
  });
});

// === 工具方法 ===
window.VOCAB_4B.getAllWords = function() {
  return this.wordLists.slice();
};

