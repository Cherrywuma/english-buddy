// 统计总数
window.PHRASES.meta.total = window.PHRASES.scenes.reduce((s, sc) => s + sc.phrases.length, 0);

// 获取所有句型
window.PHRASES.getAll = function() {
  const all = [];
  this.scenes.forEach(sc => {
    sc.phrases.forEach(p => {
      all.push({ ...p, sceneId: sc.id, sceneName: sc.name, sceneIcon: sc.icon });
    });
  });
  return all;
};

// 按级别过滤 (1=基础, 2=进阶)
window.PHRASES.getByLevel = function(level) {
  return this.getAll().filter(p => p.level === level);
};

// 按场景
window.PHRASES.getByScene = function(sceneId) {
  const sc = this.scenes.find(s => s.id === sceneId);
  return sc ? sc.phrases : [];
};
